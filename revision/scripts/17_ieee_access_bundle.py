"""Self-contained IEEE Access upload bundle of the shortened manuscript (v2).

* main.tex : main_access_v2.tex with every \\input (sections, generated macros
             and tables) inlined and the bibliography (.bbl) embedded, so the
             file compiles without the repository;
* figures  : flat file names next to main.tex;
* class    : ieeeaccess.cls and its images/ (provisional copy; see README);
* PDFs     : the manuscript compiled FROM THE BUNDLE, and the supplement.

The bundle is compiled in a clean temporary directory and its text is compared
with paper/main_access_v2.pdf; the script fails if they differ.

Run after paper/build.sh:  python scripts/17_ieee_access_bundle.py
Out: submission_ieee_access/ and submission_ieee_access.zip
"""

from __future__ import annotations

import re
import shutil
import subprocess
import sys
import tempfile
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
PAPER = ROOT / "paper"
OUT = ROOT / "submission_ieee_access"
FIGS = {"figs/v2_workflow.pdf": "fig1_workflow.pdf", "figs/v2_eddqn.pdf": "fig2_eddqn_architecture.pdf",
        "figs/v2_protocol.pdf": "fig3_evaluation_protocol.pdf", "figs/posthoc_roc.pdf": "fig4_roc.pdf",
        "figs/posthoc_cost_curves.pdf": "fig5_cost_curves.pdf"}


def inline(text: str, base: Path, depth=0) -> str:
    def rep(m):
        name = m.group(1)
        f = base / (name if name.endswith(".tex") else name + ".tex")
        if not f.exists():
            raise SystemExit(f"missing input {f}")
        body = inline(f.read_text(), base, depth + 1)
        return f"% ---- begin {name}\n{body.rstrip()}\n% ---- end {name}\n"
    # skip commented-out lines
    lines = []
    for line in text.split("\n"):
        if line.lstrip().startswith("%"):
            lines.append(line)
        else:
            lines.append(re.sub(r"\\input\{([^}]+)\}", rep, line))
    return "\n".join(lines)


def pdftext(p: Path) -> str:
    t = subprocess.run(["pdftotext", str(p), "-"], capture_output=True, text=True).stdout
    return re.sub(r"\s+", " ", t)


def main():
    if OUT.exists():
        shutil.rmtree(OUT)
    OUT.mkdir()
    tex = inline((PAPER / "main_access_v2.tex").read_text(), PAPER)
    for old, new in FIGS.items():
        tex = tex.replace("{" + old + "}", "{" + new + "}")
        shutil.copy(PAPER / old, OUT / new)
    left = re.findall(r"\\includegraphics(?:\[[^]]*\])?\{([^}]+)\}", tex)
    assert set(left) <= set(FIGS.values()), left
    bbl = (PAPER / "main_access_v2.bbl").read_text()
    tex = re.sub(r"\\bibliographystyle\{IEEEtran\}\s*\n\\bibliography\{refs\}",
                 lambda m: "% bibliography embedded from main_access_v2.bbl (IEEEtran style; source: refs.bib)\n" + bbl,
                 tex)
    tex = tex.replace("\\graphicspath{{./}{access_template/}}", "\\graphicspath{{./}}")
    header = ("% IEEE Access submission: single-file LaTeX source of the manuscript.\n"
              "% Generated by scripts/17_ieee_access_bundle.py from paper/main_access_v2.tex; edit the\n"
              "% repository sources, not this file. Compile: pdflatex main.tex (twice).\n")
    (OUT / "main.tex").write_text(header + tex)
    assert "\\input{" not in re.sub(r"%.*", "", tex), "unresolved \\input"
    shutil.copy(PAPER / "refs.bib", OUT / "refs.bib")
    shutil.copy(PAPER / "access_template" / "ieeeaccess.cls", OUT / "ieeeaccess.cls")
    shutil.copytree(PAPER / "access_template" / "images", OUT / "images")
    shutil.copy(PAPER / "supplement" / "supplement_v2.pdf", OUT / "Supplementary_Material.pdf")

    # compile the bundle alone and compare with the repository build
    with tempfile.TemporaryDirectory() as d:
        d = Path(d)
        for f in OUT.iterdir():
            (shutil.copytree if f.is_dir() else shutil.copy)(f, d / f.name)
        for _ in range(3):
            r = subprocess.run(["pdflatex", "-interaction=nonstopmode", "main.tex"], cwd=d, capture_output=True, text=True)
        log = (d / "main.log").read_text(errors="ignore")
        errs = [l for l in log.splitlines() if l.startswith("!")]
        assert not errs and (d / "main.pdf").exists(), errs[:5]
        assert "undefined" not in re.sub(r"Font shape.*undefined", "", log), "undefined references in bundle build"
        a, b = pdftext(d / "main.pdf"), pdftext(PAPER / "main_access_v2.pdf")
        same = a == b
        if not same:
            import difflib
            diff = [x for x in difflib.ndiff(b.split(" "), a.split(" ")) if x[:1] in "+-"][:40]
            raise SystemExit(f"bundle PDF text differs from paper/main_access_v2.pdf: {diff}")
        shutil.copy(d / "main.pdf", OUT / "Manuscript.pdf")
    # IEEE Access cover letter, filled from the same macros as the paper
    import importlib.util
    spec = importlib.util.spec_from_file_location("pkg", ROOT / "scripts" / "12_make_submission_package.py")
    pkg = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(pkg)
    pkg.render(ROOT / "submission" / "cover_letter_ieee_access_template.md", OUT / "Cover_letter_draft.md", pkg.macros())
    zf = shutil.make_archive(str(ROOT / "submission_ieee_access"), "zip", OUT)
    print("bundle OK: PDF text identical to paper/main_access_v2.pdf;", zf)
    for f in sorted(OUT.rglob("*")):
        if f.is_file():
            print(f"  {f.relative_to(OUT)}  {f.stat().st_size/1024:.0f} KB")


if __name__ == "__main__":
    sys.exit(main())
